/**
 * Builds `src/lib/design-assets.generated.ts`: the glyph outlines frame text
 * is drawn with, and the preset logo marks.
 *
 * Generated once and committed, so the app imports plain data: no font parser
 * or icon package at runtime, and the browser preview and the server's
 * download draw text and logos from the same outlines. Text is drawn as
 * outlines because the PNG renderer on a server has no fonts to draw it with.
 *
 *   npm run design:assets
 *
 * Sources, both free to use:
 * - Inter Bold (SIL Open Font License 1.1), from @fontsource/inter. Not the
 *   brand's own Sarlotte, whose licence was never checked for outlining text
 *   into artwork customers print.
 * - Simple Icons (CC0 1.0) for the platform marks. The marks remain their
 *   owners' trademarks; Simple Icons removes any a brand asks it to, which is
 *   why the Twitter bird and Outlook are absent and X and a generic envelope
 *   stand in.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import opentype from "opentype.js";
import * as icons from "simple-icons";

/** Every character frame text may use. The schema refuses anything else. */
const CHARSET =
  " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~₦€£’";

const PRESETS: { id: string; label: string; icon: keyof typeof icons }[] = [
  { id: "x", label: "X", icon: "siX" },
  { id: "youtube", label: "YouTube", icon: "siYoutube" },
  { id: "instagram", label: "Instagram", icon: "siInstagram" },
  { id: "tiktok", label: "TikTok", icon: "siTiktok" },
  { id: "linkedin", label: "LinkedIn", icon: "siLinkedin" },
  { id: "pinterest", label: "Pinterest", icon: "siPinterest" },
  { id: "apple", label: "Apple", icon: "siApple" },
  { id: "gmail", label: "Gmail", icon: "siGmail" },
  { id: "whatsapp", label: "WhatsApp", icon: "siWhatsapp" },
  { id: "facebook", label: "Facebook", icon: "siFacebook" },
  { id: "netflix", label: "Netflix", icon: "siNetflix" },
];

/** A plain envelope, drawn here, standing in for Outlook. 24×24 like the icons. */
const ENVELOPE =
  "M2 5.5A1.5 1.5 0 0 1 3.5 4h17A1.5 1.5 0 0 1 22 5.5v13a1.5 1.5 0 0 1-1.5 1.5h-17A1.5 1.5 0 0 1 2 18.5zm2.4.5 7.6 6.1L19.6 6zM4 8.1V18h16V8.1l-8 6.4z";

function main() {
  // Fontsource splits the font by script. Latin lacks the naira sign, which
  // Latin Extended has; both are the same face with the same metrics, so
  // each glyph is taken from whichever file holds it.
  const load = (subset: string) => {
    const buffer = readFileSync(join(process.cwd(), `node_modules/@fontsource/inter/files/inter-${subset}-700-normal.woff`));
    return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
  };
  const font = load("latin");
  const fonts = [font, load("latin-ext")];

  const glyphs: Record<string, { a: number; d: string }> = {};
  const missing: string[] = [];
  for (const char of CHARSET) {
    const glyph = fonts.map((face) => face.charToGlyph(char)).find((found) => found && found.index !== 0);
    if (!glyph) {
      missing.push(char);
      continue;
    }
    // Drawn at the font's own size, baseline at y=0, so the layout code
    // scales and places it; y grows downward as in SVG.
    const d = glyph.getPath(0, 0, font.unitsPerEm).toPathData(0);
    glyphs[char] = { a: glyph.advanceWidth ?? 0, d };
  }
  if (missing.length > 0) throw new Error(`Font lacks: ${missing.join(" ")}`);

  const logos: Record<string, { label: string; hex: string; path: string }> = {};
  for (const preset of PRESETS) {
    const icon = icons[preset.icon] as { hex: string; path: string } | undefined;
    if (!icon) throw new Error(`Simple Icons has no ${preset.icon}`);
    logos[preset.id] = { label: preset.label, hex: `#${icon.hex.toUpperCase()}`, path: icon.path };
  }
  logos.email = { label: "Email", hex: "#0B6FCC", path: ENVELOPE };

  const out = `// Generated by scripts/build-design-assets.ts. Do not edit by hand.
// Inter Bold glyph outlines (SIL Open Font License 1.1) and Simple Icons
// marks (CC0 1.0; the marks are their owners' trademarks).

export const FRAME_FONT = ${JSON.stringify({
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    capHeight: (font.tables.os2 as { sCapHeight?: number }).sCapHeight ?? Math.round(font.ascender * 0.7),
    glyphs,
  })} as const;

export const PRESET_LOGO_DATA = ${JSON.stringify(logos)} as const;
`;
  writeFileSync(join(process.cwd(), "src/lib/design-assets.generated.ts"), out);
  console.log(`Wrote ${Object.keys(glyphs).length} glyphs and ${Object.keys(logos).length} logos.`);
}

main();
